def translate_description(desc: str) -> str:
    """将英文描述翻译为中文"""
    if not desc:
        return desc

    # 如果已经是中文，直接返回
    if re.search(r'[一-鿿]', desc):
        return desc

    result = desc.strip()

    # 先应用常见模式
    for pattern, replacement in COMMON_PATTERNS:
        result = re.sub(pattern, replacement, result)

    # 然后应用术语词典
    for pattern, replacement in PATTERNS:
        result = pattern.sub(replacement, result)

    # 清理多余的空格
    result = re.sub(r'\s+', ' ', result).strip()

    return result


def main():
    print("=" * 60)
    print("OBD-II 故障码描述翻译工具 V2")
    print("=" * 60)

    files = ['p_codes.csv', 'b_codes.csv', 'c_codes.csv', 'u_codes.csv', 'ev_codes.csv']

    total_translated = 0

    for filename in files:
        filepath = SEED_DIR / filename
        if not filepath.exists():
            print(f"[SKIP] {filename} not found")
            continue

        print(f"\n[PROCESS] {filename}...")

        # 读取数据
        rows = []
        translated_count = 0

        with open(filepath, 'r', encoding='utf-8-sig') as f:
            reader = csv.DictReader(f)
            fieldnames = reader.fieldnames

            for row in reader:
                desc = row.get('description', '')
                if desc and not re.search(r'[一-鿿]', desc):
                    # 英文描述，需要翻译
                    new_desc = translate_description(desc)
                    if new_desc != desc:
                        row['description'] = new_desc
                        translated_count += 1
                rows.append(row)

        # 写回文件
        with open(filepath, 'w', encoding='utf-8-sig', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction='ignore')
            writer.writeheader()
            for row in rows:
                clean_row = {k: v for k, v in row.items() if k is not None}
                writer.writerow(clean_row)

        print(f"   Translated: {translated_count} descriptions")
        total_translated += translated_count

    print(f"\n{'=' * 60}")
    print(f"翻译完成!")
    print(f"   总翻译数: {total_translated}")
    print(f"\n下一步: python scripts/seed_db.py -f")
    print(f"{'=' * 60}")


if __name__ == "__main__":
    main()
